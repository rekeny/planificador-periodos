// Bundles the migrations of drizzle-kit into src/data/migrations/bundle.ts (T027), because Metro
// cannot read .sql files at run time. Run from the project root, after `drizzle-kit generate`.
// Node built-ins only. Everything is read before anything is written, so an error never leaves
// a half-written bundle.
import { existsSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const FOLDER = "src/data/migrations";
const JOURNAL = join(FOLDER, "meta/_journal.json");
const BUNDLE = join(FOLDER, "bundle.ts");

function fail(message) {
  console.error(`bundle-migrations: ${message}`);
  process.exit(1);
}

if (!existsSync(JOURNAL)) {
  fail(
    `the journal ${JOURNAL} does not exist. Run drizzle-kit generate first.`,
  );
}

let journal;
try {
  journal = JSON.parse(readFileSync(JOURNAL, "utf8"));
} catch (error) {
  fail(`the journal ${JOURNAL} cannot be read as JSON: ${error.message}`);
}
if (!journal || !Array.isArray(journal.entries)) {
  fail(`the journal ${JOURNAL} has no "entries" list.`);
}

const migrations = {};
for (const entry of journal.entries) {
  const file = join(FOLDER, `${entry.tag}.sql`);
  if (!existsSync(file)) {
    fail(`the journal entry "${entry.tag}" has no file ${file} in ${FOLDER}.`);
  }
  try {
    migrations[`m${String(entry.idx).padStart(4, "0")}`] = readFileSync(
      file,
      "utf8",
    );
  } catch (error) {
    fail(
      `the file ${file} of the entry "${entry.tag}" cannot be read: ${error.message}`,
    );
  }
}

const text = [
  "// Generated by scripts/bundle-migrations.mjs from the SQL files and the journal. Do not edit.",
  `export default ${JSON.stringify({ journal, migrations }, null, 2)};`,
  "",
].join("\n");

const temporary = `${BUNDLE}.tmp`;
try {
  writeFileSync(temporary, text);
  renameSync(temporary, BUNDLE);
} catch (error) {
  fail(`${BUNDLE} cannot be written: ${error.message}`);
}
